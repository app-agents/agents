#!/usr/bin/env node
/**
 * Generates the spec's type registry for every app.
 *
 * `StandardAgentSpec.*Registry` defaults to `string` when empty, which means a
 * prompt can reference `tools: ['typo']` or `model: 'nope'` and still compile.
 * This script reads each package's actual exported registries — the same maps
 * the runtime resolves against — and writes a `types.d.ts` that narrows the
 * unions to those names.
 *
 * Output is deterministic and committed, so editors and CI agree without
 * anyone running this by hand.
 */
import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const appsDir = path.join(root, 'apps');

interface Packed {
  agents?: Record<string, unknown>;
  prompts?: Record<string, unknown>;
  tools?: Record<string, unknown>;
  models?: Record<string, unknown>;
}

function registryBlock(interfaceName: string, names: string[], indent = '    '): string {
  if (names.length === 0) return `${indent}interface ${interfaceName} {}`;
  const entries = names.map((name) => `${indent}  ${JSON.stringify(name)}: true;`).join('\n');
  return `${indent}interface ${interfaceName} {\n${entries}\n${indent}}`;
}

const written: string[] = [];

for (const entry of await readdir(appsDir, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;

  const indexPath = path.join(appsDir, entry.name, 'src/index.ts');
  let packed: Packed;
  try {
    packed = (await import(indexPath)) as Packed;
  } catch (error) {
    throw new Error(
      `${entry.name}: could not import src/index.ts — ${error instanceof Error ? error.message : error}`,
    );
  }

  const keys = (map: Record<string, unknown> | undefined) => Object.keys(map ?? {}).sort();
  const models = keys(packed.models);
  const prompts = keys(packed.prompts);
  const agents = keys(packed.agents);
  const tools = keys(packed.tools);
  // Callables are everything a prompt may name in `tools`.
  const callables = [...prompts, ...agents, ...tools].sort();

  const file = `// Generated by scripts/gen-types.ts — do not edit by hand.
// Regenerate: npm run gen:types
//
// Narrows the spec's type registries to the definitions this package actually
// exports, so a renamed tool or model becomes a compile error rather than a
// runtime surprise.

declare global {
  namespace StandardAgentSpec {
${registryBlock('ModelRegistry', models)}
${registryBlock('PromptRegistry', prompts)}
${registryBlock('AgentRegistry', agents)}
${registryBlock('ToolRegistry', tools)}
${registryBlock('CallableRegistry', callables)}
    interface HookIdRegistry {}
    interface HandlerRegistry {}
  }
}

export {};
`;

  const target = path.join(appsDir, entry.name, 'src/types.d.ts');
  await writeFile(target, file);
  written.push(`${entry.name}: ${models.length}m ${prompts.length}p ${agents.length}a ${tools.length}t`);
}

console.log(`types.d.ts written for ${written.length} app(s)`);
for (const line of written) console.log(`  ${line}`);
